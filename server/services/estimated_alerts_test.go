package services

import (
	"context"
	"github.com/jackc/pgx/v5/pgxpool"
	"github.com/joho/godotenv"
	"os"
	"strings"
	"testing"
	"time"
)

func TestEstimatedAlertWorkflowWithIsolatedInventory(t *testing.T) {
	path := os.Getenv("CATALOG_TEST_DB_ENV")
	if path == "" {
		t.Skip("set CATALOG_TEST_DB_ENV for PostgreSQL integration")
	}
	env, err := godotenv.Read(path)
	if err != nil {
		t.Fatal("configuration unavailable")
	}
	ctx, cancel := context.WithTimeout(context.Background(), 30*time.Second)
	defer cancel()
	config, err := pgxpool.ParseConfig(env["DB_URL"])
	if err != nil {
		t.Fatal("configuration invalid")
	}
	config.MaxConns = 1
	config.ConnConfig.RuntimeParams["qayen.test_alerts"] = "on"
	pool, err := pgxpool.NewWithConfig(ctx, config)
	if err != nil {
		t.Fatal("database unavailable")
	}
	defer pool.Close()
	// TEMP tables shadow public tables on this one connection. Copy constraints,
	// but replace SERIAL defaults so even public sequences remain untouched.
	for _, name := range []string{"users", "medications", "pharmacies", "stock", "medication_alerts", "pharmacy_alert_notifications", "pharmacist_responses", "pharmacy_analytics", "alert_rate_limits"} {
		if _, err = pool.Exec(ctx, `CREATE TEMP TABLE `+name+` (LIKE public.`+name+` INCLUDING ALL); ALTER TABLE `+name+` ALTER COLUMN id DROP DEFAULT; ALTER TABLE `+name+` ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY`); err != nil {
			t.Fatal(err)
		}
	}
	schema, err := os.ReadFile("../database/migrations/20261026000000_add_estimated_alert_testing.sql")
	if err != nil {
		t.Fatal(err)
	}
	up := strings.Split(string(schema), "-- +goose Down")[0]
	up = strings.ReplaceAll(up, "CREATE TABLE IF NOT EXISTS", "CREATE TEMP TABLE")
	up = strings.ReplaceAll(up, "CREATE OR REPLACE VIEW", "CREATE TEMP VIEW")
	if _, err = pool.Exec(ctx, up); err != nil {
		t.Fatal(err)
	}
	_, err = pool.Exec(ctx, `INSERT INTO users(id,email,name) VALUES(5001,'test@example.com','Test patient');
 INSERT INTO medications(id,speciality,active_substance) VALUES(5001,'Test medicine','Ingredient');
 INSERT INTO pharmacies(id,name,address,city,phone) VALUES(5001,'Test estimated pharmacy','52 Test Street','Marrakech','');
 INSERT INTO pharmacies(id,name,address,city,phone,latitude,longitude) VALUES(5002,'Recorded pharmacy','Existing address','Rabat','',34.02,-6.84);
 INSERT INTO stock(pharmacy_id,medication_id,quantity) VALUES(5002,5001,7);
 INSERT INTO catalog_test_locations(pharmacy_id,matched_address,latitude,longitude) VALUES(5001,'52 Test Street',31.63416,-7.99994);
 INSERT INTO catalog_test_stock(pharmacy_id,medication_id,quantity) VALUES(5001,5001,20);
 UPDATE catalog_test_settings SET enabled=true;`)
	if err != nil {
		t.Fatal(err)
	}
	t.Setenv("QAYEN_ENABLE_APPROXIMATE_ALERTS", "true")
	service := NewAlertService(pool, nil)
	alert, err := service.CreateMedicationAlert(ctx, AlertRequest{CustomerID: 5001, MedicationID: 5001, Latitude: 31.63416, Longitude: -7.99994, SearchRadius: 5, MaxResponseTime: 2, RequestedQuantity: 2})
	if err != nil {
		t.Fatal(err)
	}
	result, err := service.GetAlertResults(ctx, alert.AlertID, 31.63416, -7.99994)
	if err != nil {
		t.Fatal(err)
	}
	if len(result.Pharmacies) != 1 || result.Pharmacies[0].PharmacyID != 5001 || result.Pharmacies[0].ResponseType != "available" || !result.Pharmacies[0].EstimatedLocation || !result.Pharmacies[0].TestInventory || !result.TestMode {
		t.Fatalf("estimated pharmacy did not answer with explicit test metadata: %+v", result)
	}
	pickup, err := service.ConfirmPickup(ctx, ConfirmPickupRequest{AlertID: alert.AlertID, PharmacyID: 5001, Quantity: 2})
	if err != nil {
		t.Fatal(err)
	}
	if pickup.RemainingStock != 18 {
		t.Fatal("test stock was not decremented")
	}
	var safe bool
	err = pool.QueryRow(ctx, `SELECT (SELECT latitude IS NULL AND longitude IS NULL FROM pharmacies WHERE id=5001) AND (SELECT quantity=7 FROM stock WHERE pharmacy_id=5002) AND NOT EXISTS(SELECT 1 FROM stock WHERE pharmacy_id=5001)`).Scan(&safe)
	if err != nil || !safe {
		t.Fatalf("real GPS or inventory changed: %v", err)
	}
	// A linked pharmacist uses the manual dashboard/response path instead of
	// automatic stock simulation, with the same estimated search distance.
	if _, err = pool.Exec(ctx, `INSERT INTO users(id,email,name,managed_pharmacy_id) VALUES(5002,'pharmacist-test@example.com','Test pharmacist',5001)`); err != nil {
		t.Fatal(err)
	}
	manual, err := service.CreateMedicationAlert(ctx, AlertRequest{CustomerID: 5001, MedicationID: 5001, Latitude: 31.63416, Longitude: -7.99994, SearchRadius: 5, MaxResponseTime: 2, RequestedQuantity: 1})
	if err != nil {
		t.Fatal(err)
	}
	dashboard, err := service.GetPharmacyDashboardAlerts(ctx, 5001)
	if err != nil || len(dashboard) != 1 || dashboard[0].AlreadyResponded {
		t.Fatalf("manual estimated dashboard failed: %v / %+v", err, dashboard)
	}
	if err = service.SubmitPharmacistResponse(ctx, PharmacistResponseRequest{AlertID: manual.AlertID, PharmacyID: 5001, ResponseType: "available"}); err != nil {
		t.Fatal(err)
	}
	manualResult, err := service.GetAlertResults(ctx, manual.AlertID, 31.63416, -7.99994)
	if err != nil || len(manualResult.Pharmacies) != 1 || !manualResult.Pharmacies[0].EstimatedLocation {
		t.Fatal("manual estimated response missing")
	}
	// Production sessions and the database kill-switch both exclude estimates.
	if _, err = pool.Exec(ctx, `SET qayen.test_alerts='off'`); err != nil {
		t.Fatal(err)
	}
	err = pool.QueryRow(ctx, `SELECT (SELECT latitude IS NULL FROM alert_pharmacy_locations WHERE id=5001) AND NOT EXISTS(SELECT 1 FROM alert_stock WHERE pharmacy_id=5001)`).Scan(&safe)
	if err != nil || !safe {
		t.Fatal("test data leaked into disabled session")
	}
	if _, err = pool.Exec(ctx, `SET qayen.test_alerts='on'; UPDATE catalog_test_settings SET enabled=false`); err != nil {
		t.Fatal(err)
	}
	err = pool.QueryRow(ctx, `SELECT latitude IS NULL FROM alert_pharmacy_locations WHERE id=5001`).Scan(&safe)
	if err != nil || !safe {
		t.Fatal("database kill-switch failed")
	}
	t.Setenv("QAYEN_ENABLE_APPROXIMATE_ALERTS", "false")
	production := NewAlertService(pool, nil)
	if _, err = production.GetAlertResults(ctx, manual.AlertID, 31.63416, -7.99994); err == nil {
		t.Fatal("disabled mode exposed a saved test alert")
	}
}
