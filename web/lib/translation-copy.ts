function normalize(text: string): string {
  return text.normalize("NFKC").replace(/[’‘]/g, "'").replace(/…/g, "...").replace(/\s+/g, " ").trim().toLowerCase();
}

const englishCopy = new Map<string, readonly [string, string, string]>();
const frenchCopy = new Map<string, readonly [string, string, string]>();
for (const entry of UI_TRANSLATIONS) {
  englishCopy.set(normalize(entry[0]), entry);
  frenchCopy.set(normalize(entry[1]), entry);
}

/** Returns undefined for content that still needs automatic translation. */
export function getUiTranslation(text: string, language: TranslationLanguage): string | undefined {
  if (language === "en") return text;
  const key = normalize(text);
  const index = language === "fr" ? 1 : 2;
  const findEntry = (value: string) => englishCopy.get(value) ?? frenchCopy.get(value);
  const entry = findEntry(key);
  if (entry) return entry[index];

  // Reuse a label's wording for variants such as "Quantity:" and "Pickup confirmed.".
  const punctuated = key.match(/^(.+?)([:.!?]+)$/);
  if (punctuated) {
    const base = findEntry(punctuated[1]);
    if (base) return `${base[index]}${punctuated[2]}`;
  }

  // Contact values must remain intact while their surrounding labels are translated.
  const contact = text.trim().match(/^(Email|Phone):\s*(.+)$/i);
  if (contact) return `${getUiTranslation(contact[1], language)}: ${contact[2]}`;

  const distance = key.match(/^(\d+(?:[.,]\d+)?)\s+(km away|km|miles?)$/);
  if (distance) {
    const unit = distance[2].startsWith("mile") ? (language === "ar" ? "ميل" : "miles") : "km";
    return `${distance[1]} ${unit === "km" && language === "ar" ? "كم" : unit}`;
  }
  const time = text.trim().match(/^(\d{1,2}:\d{2})\s*(AM|PM)$/i);
  if (time) {
    const hour = Number(time[1].split(":")[0]) % 12 + (time[2].toLowerCase() === "pm" ? 12 : 0);
    return language === "ar"
      ? `${time[1]} ${time[2].toLowerCase() === "pm" ? "م" : "ص"}`
      : `${String(hour).padStart(2, "0")}:${time[1].split(":")[1]}`;
  }
  const welcome = text.trim().match(/^Welcome back, (.+)!$/);
  if (welcome) return language === "ar" ? `مرحبًا بعودتك، ${welcome[1]}!` : `Bon retour, ${welcome[1]} !`;

  const stockResponse = text.trim().match(/^(.+) \(ID: (\d+)\) (has it in stock|suggested a substitute|doesn't have it in stock)\.$/);
  if (stockResponse) {
    const [, name, id, response] = stockResponse;
    const responseCopy = response === "has it in stock"
      ? ["dispose de ce médicament en stock", "يتوفر لديها هذا الدواء في المخزون"]
      : response === "suggested a substitute"
        ? ["a proposé une alternative", "اقترحت دواءً بديلًا"]
        : ["ne dispose pas de ce médicament en stock", "لا يتوفر لديها هذا الدواء في المخزون"];
    return language === "ar" ? `${name} (الرقم: ${id}) ${responseCopy[1]}.` : `${name} (ID : ${id}) ${responseCopy[0]}.`;
  }
  const insufficientStock = text.trim().match(/^(.+) only has (\d+) available\.$/);
  if (insufficientStock) return language === "ar"
    ? `لا تتوفر لدى ${insufficientStock[1]} سوى ${insufficientStock[2]} وحدة.`
    : `${insufficientStock[1]} ne dispose que de ${insufficientStock[2]} unité(s).`;

  const pickup = text.trim().match(/^You're all set to pick up (\d+) from (.+)\.$/);
  if (pickup) return language === "ar"
    ? `يمكنك الآن استلام ${pickup[1]} وحدة من ${pickup[2]}.`
    : `Vous pouvez retirer ${pickup[1]} unité(s) auprès de ${pickup[2]}.`;

  const quantityRange = text.trim().match(/^Please choose between 1 and (\d+)\.$/);
  if (quantityRange) return language === "ar"
    ? `يرجى اختيار كمية بين 1 و${quantityRange[1]}.`
    : `Choisissez une quantité entre 1 et ${quantityRange[1]}.`;

  const reserved = text.trim().match(/^(\d+) items? reserved\. Remaining pharmacy stock: (\d+)\.$/);
  if (reserved) return language === "ar"
    ? `تم حجز ${reserved[1]} وحدة. المخزون المتبقي في الصيدلية: ${reserved[2]}.`
    : `${reserved[1]} unité(s) réservée(s). Stock restant en pharmacie : ${reserved[2]}.`;

  const notifying = text.trim().match(/^Notifying nearby pharmacies about (.+)$/);
  if (notifying) return language === "ar"
    ? `جارٍ إشعار الصيدليات القريبة بطلب ${notifying[1]}`
    : `Envoi d'une demande aux pharmacies à proximité pour ${notifying[1]}`;

  const addedStock = text.trim().match(/^(.+) added to your stock$/);
  if (addedStock) return language === "ar"
    ? `تمت إضافة ${addedStock[1]} إلى مخزونك`
    : `${addedStock[1]} ajouté à votre stock`;

  const alertStatus = text.trim().match(/^Alert marked as (available|unavailable)$/);
  if (alertStatus) return language === "ar"
    ? `تم تحديث حالة التنبيه إلى: ${getUiTranslation(alertStatus[1], language)}`
    : `Statut de l'alerte : ${getUiTranslation(alertStatus[1], language)}`;

  const responseSent = text.trim().match(/^You responded "(available|unavailable|substitute)" to the medication request$/);
  if (responseSent) return language === "ar"
    ? `أجبت عن طلب الدواء بالحالة: ${getUiTranslation(responseSent[1], language)}`
    : `Votre réponse à la demande de médicament : ${getUiTranslation(responseSent[1], language)}`;
  if (key === "(id:") return language === "ar" ? "(الرقم:" : "(ID :";
  return undefined;
}
